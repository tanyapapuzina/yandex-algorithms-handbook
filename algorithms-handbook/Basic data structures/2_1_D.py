
"""
D. Префиксные минимумы.

Сложность: O(n) по времени, O(n) по памяти.

Для каждой позиции i нужно вывести минимум среди всех элементов от начала
массива до этой позиции: min(a[1], ..., a[i]).

Достаточно пройти по массиву один раз и хранить текущий минимум. Если новый
элемент меньше текущего минимума, обновляем его. После каждого шага добавляем
текущий минимум в ответ.
"""


n = int(input())
a = list(map(int, input().split()))

b = a[0]
answer = []

for i in range(n):
    if a[i] < b:
        b = a[i]

    answer.append(b)

print(*answer)
